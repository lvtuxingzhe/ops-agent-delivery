-- 007_identity_v3.sql
-- 把认证类数据收敛到 v3_users 体系。
--
-- 这个文件【只做新增与拷贝】，不 DROP、不改旧表。删旧表由 008 迁移负责，
-- 必须等后端代码切到 v3_* 之后才允许执行。
--
-- 为什么保留「凭据与资料分离」：
--   v3_users 是资料（名字、角色、是否启用），凭据单独一张表。
--   查询用户列表时不触碰密码哈希，也不会因为一次 JOIN 把密钥带进日志。
--
-- id 对齐的前提：users.id 与 v3_users.id 均为 1/2，
-- username 一一对应，v3_users.roles 与 user_roles 一致。若换成别的环境，
-- 这里的 JOIN 依然按 username 匹配，不假设 id 相同。

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. 凭据表：密码哈希、TOTP、锁定状态
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS v3_auth_credentials (
    user_id          bigint PRIMARY KEY REFERENCES v3_users(id) ON DELETE CASCADE,
    password_hash    text NOT NULL DEFAULT '',      -- 空串 = 未启用密码登录，不是「可以登录」
    totp_secret_enc  text,
    totp_enabled     boolean NOT NULL DEFAULT false,
    totp_bound_at    timestamptz,
    failed_attempts  integer NOT NULL DEFAULT 0,
    locked_until     timestamptz,
    updated_at       timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- 2. 角色标志：v3_users.roles 只存角色代码，自审批豁免这类「角色属性」放这里
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS v3_role_flags (
    code             text PRIMARY KEY,
    name             text NOT NULL,
    can_self_approve boolean NOT NULL DEFAULT false
);

-- ---------------------------------------------------------------------------
-- 3. 手机绑定：一个手机号只能绑一个账号
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS v3_phone_bindings (
    user_id   bigint PRIMARY KEY REFERENCES v3_users(id) ON DELETE CASCADE,
    phone     text NOT NULL UNIQUE,
    bound_at  timestamptz NOT NULL DEFAULT now(),
    bound_by  bigint REFERENCES v3_users(id)
);

-- ---------------------------------------------------------------------------
-- 3. 短信码：一次性，靠 used_at 判消费
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS v3_sms_codes (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone       text NOT NULL,
    code_hash   text NOT NULL,
    trace_id    text,
    expires_at  timestamptz NOT NULL,
    used_at     timestamptz,
    attempts    integer NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now(),
    -- 同一手机号 + 同一哈希视为同一条码：迁移可重复执行，不会重复灌入
    CONSTRAINT uq_v3_sms_codes_phone_hash UNIQUE (phone, code_hash)
);
CREATE INDEX IF NOT EXISTS idx_v3_sms_codes_phone_created
    ON v3_sms_codes (phone, created_at DESC);

-- ---------------------------------------------------------------------------
-- 4. 二次确认令牌：绑定到 v3_tasks，不再有 plan_id（旧计划表要删）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS v3_confirmation_tokens (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id           uuid REFERENCES v3_tasks(id) ON DELETE CASCADE,
    plan_fingerprint  text,
    token_hash        text NOT NULL UNIQUE,
    step_up_method    text NOT NULL,
    is_self_approval  boolean NOT NULL DEFAULT false,
    expires_at        timestamptz NOT NULL,
    used_at           timestamptz,
    created_at        timestamptz NOT NULL DEFAULT now()
);
-- 分批上线时旧表仍在：已经建过的库补列，保证脚本可重复执行
ALTER TABLE v3_confirmation_tokens
    ADD COLUMN IF NOT EXISTS plan_fingerprint text;

-- ---------------------------------------------------------------------------
-- 5. 拷贝存量（按 username 关联，不假设 id 相同）
-- ---------------------------------------------------------------------------
INSERT INTO v3_auth_credentials (
    user_id, password_hash, totp_secret_enc, totp_enabled,
    totp_bound_at, failed_attempts, locked_until, updated_at
)
SELECT
    v.id,
    COALESCE(a.password_hash, ''),            -- 旧占位串已清掉，这里原样搬
    a.totp_secret_enc,
    COALESCE(a.totp_enabled, false),
    a.totp_bound_at,
    COALESCE(a.failed_attempts, 0),
    a.locked_until,
    COALESCE(a.updated_at, now())
FROM auth_credentials a
JOIN users u      ON u.id = a.user_id
JOIN v3_users v   ON v.username = u.username
ON CONFLICT (user_id) DO NOTHING;

INSERT INTO v3_phone_bindings (user_id, phone, bound_at, bound_by)
SELECT
    v.id,
    p.phone,
    COALESCE(p.bound_at, now()),
    (SELECT v2.id
       FROM v3_users v2
       JOIN users u2 ON u2.username = v2.username
      WHERE u2.id = p.bound_by)
FROM phone_bindings p
JOIN users u      ON u.id = p.user_id
JOIN v3_users v   ON v.username = u.username
ON CONFLICT (user_id) DO NOTHING;

INSERT INTO v3_sms_codes (phone, code_hash, trace_id, expires_at, used_at, attempts, created_at)
SELECT phone, code_hash, trace_id, expires_at, used_at,
       COALESCE(attempts, 0), COALESCE(created_at, now())
FROM sms_codes
ON CONFLICT (phone, code_hash) DO NOTHING;

INSERT INTO v3_confirmation_tokens (
    task_id, plan_fingerprint, token_hash, step_up_method,
    is_self_approval, expires_at, used_at, created_at
)
SELECT c.task_id, p.fingerprint, c.token_hash, c.step_up_method,
       COALESCE(c.is_self_approval, false), c.expires_at, c.used_at,
       COALESCE(c.created_at, now())
FROM confirmation_tokens c
JOIN v3_tasks t ON t.id = c.task_id          -- 任务不存在的令牌不搬（外键会拒）
LEFT JOIN plans p ON p.id = c.plan_id         -- 方案指纹一起带过来，旧计划表随即可删
ON CONFLICT (token_hash) DO NOTHING;

INSERT INTO v3_role_flags (code, name, can_self_approve)
SELECT code, name, can_self_approve FROM roles
ON CONFLICT (code) DO UPDATE
    SET name = EXCLUDED.name,
        can_self_approve = EXCLUDED.can_self_approve;

-- ---------------------------------------------------------------------------
-- 6. 角色与 MFA 标志对齐（以旧表为准复核，不一致就纠正）
-- ---------------------------------------------------------------------------
UPDATE v3_users v
SET roles = sub.codes
FROM (
    SELECT u.username, array_agg(r.code ORDER BY r.code) AS codes
      FROM user_roles ur
      JOIN users u ON u.id = ur.user_id
      JOIN roles r ON r.id = ur.role_id
     GROUP BY u.username
) AS sub
WHERE v.username = sub.username
  AND v.roles IS DISTINCT FROM sub.codes;

UPDATE v3_users v
SET mfa_enabled = c.totp_enabled
FROM v3_auth_credentials c
WHERE c.user_id = v.id
  AND v.mfa_enabled IS DISTINCT FROM c.totp_enabled;

COMMIT;

